import type { GameMap, MapNote } from './types';
import { SAMPLE_BPM } from '../audio/testSound';

const BEAT = 60 / SAMPLE_BPM;

/** [박(beat), 레인(0~3), 롱노트 길이(박, 생략하면 탭)] — 고정 샘플 맵 (120 BPM, 16마디) */
const PATTERN: ReadonlyArray<readonly [number, number, number?]> = [
  // 2마디: 느린 탭
  [4, 1], [5, 2], [6, 1], [7, 2],
  // 3~4마디: 계단
  [8, 0], [9, 1], [10, 2], [11, 3],
  [12, 3], [13, 2], [14, 1], [15, 0],
  // 5~6마디: 8분음표
  [16, 0], [16.5, 1], [17, 2], [17.5, 3], [18, 2], [18.5, 1], [19, 0], [19.5, 3],
  [20, 1], [20.5, 2], [21, 1], [21.5, 2], [22, 0], [22.5, 3], [23, 0], [23.5, 3],
  // 7마디: 롱노트 2개 동시
  [24, 0, 2], [24, 3, 2], [26, 1], [27, 2],
  // 8마디: 롱노트를 누른 채 다른 손으로 탭 (멀티터치)
  [28, 1, 3], [29, 3], [30, 3], [31, 3],
  // 9~10마디: 동시치기 + 8분 계단
  [32, 0], [32, 3], [33, 1], [33, 2], [34, 0], [34, 3], [35, 1], [35, 2],
  [36, 0], [36.5, 1], [37, 2], [37.5, 3], [38, 3], [38.5, 2], [39, 1], [39.5, 0],
  // 11~12마디: 짧은 롱노트 섞기
  [40, 0, 1.5], [41.5, 3], [42, 1, 1.5], [43.5, 2],
  [44, 1], [44.5, 2], [45, 1], [45.5, 2], [46, 0], [46, 3], [47, 1], [47, 2],
  // 13마디: 16분음표 연타
  [48, 0], [48.25, 1], [48.5, 2], [48.75, 3], [49, 2], [49.25, 1], [49.5, 0], [49.75, 1],
  [50, 0], [50, 3], [51, 1], [51, 2],
  // 14~15마디
  [52, 0, 2], [52, 3, 2], [54, 1], [54.5, 2], [55, 1], [55.5, 2],
  [56, 0], [56.5, 1], [57, 2], [57.5, 3], [58, 0], [58.5, 1], [59, 2], [59.5, 3],
  // 16마디: 피날레
  [60, 0], [60, 3], [61, 1], [61, 2], [62, 0], [62, 3],
];

const notes: MapNote[] = PATTERN.map(([beat, lane, durBeats]) => ({
  t: beat * BEAT,
  lane,
  dur: (durBeats ?? 0) * BEAT,
})).sort((a, b) => a.t - b.t || a.lane - b.lane);

export const SAMPLE_MAP: GameMap = {
  songHash: 'sample-builtin',
  title: 'Test Beat (120 BPM)',
  bpm: SAMPLE_BPM,
  difficulty: 'normal',
  notes,
};
